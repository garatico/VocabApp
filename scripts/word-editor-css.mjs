#!/usr/bin/env node
/**
 * word-editor-css.mjs — derives public/styles/app/word-editor.css.
 *
 * The shared Word Editor (src/client/ui/word-editor/) was built for the Admin
 * panel, whose stylesheets style bare elements (`button`, `input`, `select`)
 * and generic classes (`.badge`, `.hint`, `.filter-bar`) globally — fine in a
 * page of its own, not in the main app, where those would restyle everything.
 *
 * So the Admin stylesheets stay the single source of truth, and this script
 * writes a copy for the app with every selector prefixed by `.word-editor`,
 * the class My Content puts on the editor's container. tests/client/
 * word-editor-css.test.ts fails if the checked-in copy drifts from its sources
 * — run `npm run build:word-editor-css` and commit the result.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const SOURCES = [
  'public/styles/admin/inputs.css',
  'public/styles/admin/buttons.css',
  'public/styles/admin/filter-bar.css',
  'public/styles/admin/word-list.css',
  'public/styles/admin/edit-form.css',
];
export const OUTPUT = 'public/styles/app/word-editor.css';
export const SCOPE = '.word-editor';

/** Splits on top-level commas only (not inside (), [] — `:is(a, b)`, `[x="a,b"]`). */
function splitSelectors(list) {
  const out = [];
  let depth = 0; let cur = '';
  for (const ch of list) {
    if (ch === '(' || ch === '[') depth++;
    if (ch === ')' || ch === ']') depth--;
    if (ch === ',' && depth === 0) { out.push(cur); cur = ''; } else cur += ch;
  }
  if (cur.trim()) out.push(cur);
  return out.map(s => s.trim()).filter(Boolean);
}

function scopeSelector(sel) {
  if (sel === 'html' || sel === 'body' || sel === ':root') return SCOPE;
  // `html.dark .x` → `html.dark .word-editor .x`: keep the theme class outside the scope.
  const dark = /^(html\.dark|\.dark)\s+(.*)$/.exec(sel);
  if (dark) return `${dark[1]} ${SCOPE} ${dark[2]}`;
  return `${SCOPE} ${sel}`;
}

/** Recursively scopes the rules in `css`, leaving at-rules' own preludes alone. */
function scopeBlock(css) {
  let out = '';
  let i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open === -1) { out += css.slice(i); break; }
    const prelude = css.slice(i, open).trim();
    // find the matching close brace
    let depth = 1; let j = open + 1;
    while (j < css.length && depth > 0) {
      if (css[j] === '{') depth++;
      else if (css[j] === '}') depth--;
      j++;
    }
    const body = css.slice(open + 1, j - 1);
    if (prelude.startsWith('@media') || prelude.startsWith('@supports')) {
      out += `${prelude} {\n${scopeBlock(body).replace(/^/gm, '  ')}\n}\n`;
    } else if (prelude.startsWith('@')) {
      out += `${prelude} {${body}}\n`;          // @keyframes, @font-face — not selector-scoped
    } else {
      const scoped = splitSelectors(prelude).map(scopeSelector).join(',\n');
      out += `${scoped} {${body}}\n`;
    }
    i = j;
  }
  return out;
}

export function buildWordEditorCss(read = f => readFileSync(resolve(root, f), 'utf8')) {
  const parts = SOURCES.map(f => {
    const css = read(f).replace(/\r\n/g, '\n').replace(/\/\*[\s\S]*?\*\//g, '');
    return `/* ── from ${f} ── */\n${scopeBlock(css)}`;
  });
  return `/* GENERATED by scripts/word-editor-css.mjs — do not edit.
   The shared Word Editor's styles, copied from the Admin panel's stylesheets
   with every selector scoped under ${SCOPE}. Edit the Admin sources and run
   \`npm run build:word-editor-css\`. */

${parts.join('\n')}`.replace(/\n{3,}/g, '\n\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(resolve(root, OUTPUT), buildWordEditorCss());
  console.log(`wrote ${OUTPUT}`);
}
