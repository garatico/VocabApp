"""
hardcoded_data.py
=================
Curated word lists for the VocabApp data pipeline.

Contains ALL data that cannot be reliably sourced from Wikipedia frequency
corpora — i.e. everything that is either:

  • Closed-class (function words): articles, prepositions, conjunctions,
    pronouns, possessives, demonstratives, interrogatives, closed-class adverbs.
    These are a finite, stable set deliberately absent or underrepresented in
    corpus data (Wikipedia is encyclopaedic, not conversational).

  • Irregular verbs: the ~40 most important verbs whose stems change
    unpredictably across tenses.  Conjugations are generated at build time
    by mlconjug3 in clean_wikicorpora.py.

  • Languages covered: Spanish (spa), French (fra), Italian (ita),
    Portuguese (por).

Editing guide
─────────────
  fw(word, pos, glosses, lang, band='A1', difficulty=1, notes='', domains=None)
      → function word entry (articles, prepositions, conjunctions, pronouns, adverbs)

  irr(word, glosses, lang, band='A1', difficulty=1, notes='')
      → irregular verb entry (conjugations filled later by mlconjug3)

  LANGUAGE_DATA — registry mapping ISO-639-3 code → lists; imported by
                  clean_wikicorpora.py.

Do NOT put open-class content here (regular nouns/verbs/adjectives).
Those come from the Wikipedia corpus pipeline in clean_wikicorpora.py.
"""

from typing import Dict, List, Optional


# ══════════════════════════════════════════════════════════════════════════════
# ENTRY FACTORIES
# ══════════════════════════════════════════════════════════════════════════════

def fw(word: str, pos: str, glosses: List[str], lang: str,
       band: str = 'A1', difficulty: int = 1,
       notes: str = '', domains: Optional[List[str]] = None) -> dict:
    """Build a hardcoded function-word entry."""
    return {
        'rank':       None,
        'word':       word,
        'display':    glosses[0] if glosses else '',
        'pos':        pos,
        'difficulty': difficulty,
        'tags':       ['hardcoded', 'function_word'],
        'notes':      notes,
        'glosses':    glosses,
        'examples':   [],
        'linguistic': {
            'infinitive':   None,
            'reflexive':    None,
            'gender':       None,
            'plural':       None,
            'register':     'neutral',
            'ipa':          '',
            'syllables':    [],
            'conjugations': None,
            'irregular':    False,
        },
        'relations':  {'commonly_confused_with': [], 'related': [], 'synonyms': [], 'antonyms': []},
        'frequency':  {'band': band, 'rank': None, 'corpus_frequency': None},
        'domains':    domains or ['general'],
        'register':   'neutral',
        'lang':       lang,
        'source':     'hardcoded',
        'needs_review': False,
    }


def irr(word: str, glosses: List[str], lang: str,
        band: str = 'A1', difficulty: int = 1,
        notes: str = '') -> dict:
    """Build a hardcoded irregular-verb entry (conjugations filled by mlconjug3)."""
    return {
        'rank':       None,
        'word':       word,
        'display':    glosses[0] if glosses else '',
        'pos':        'verb',
        'difficulty': difficulty,
        'tags':       ['hardcoded', 'irregular'],
        'notes':      notes,
        'glosses':    glosses,
        'examples':   [],
        'linguistic': {
            'infinitive':   word,
            'reflexive':    None,
            'gender':       None,
            'plural':       None,
            'register':     'neutral',
            'ipa':          '',
            'syllables':    [],
            'conjugations': None,   # filled by build_conjugations() in clean_wikicorpora.py
            'irregular':    True,
        },
        'relations':  {'commonly_confused_with': [], 'related': [], 'synonyms': [], 'antonyms': []},
        'frequency':  {'band': band, 'rank': None, 'corpus_frequency': None},
        'domains':    ['general'],
        'register':   'neutral',
        'lang':       lang,
        'source':     'hardcoded',
        'needs_review': False,
    }


